package nl.kmc.kmccore.achievements;

import com.destroystokyo.paper.event.player.PlayerAdvancementCriterionGrantEvent;
import nl.kmc.kmccore.KMCCore;
import org.bukkit.Bukkit;
import org.bukkit.advancement.Advancement;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;

/**
 * Keeps the normal Minecraft advancements out of a tournament: nothing from the vanilla namespace is ever
 * granted, so no toast pops up and nothing is announced; only the KMC achievements show. Recipe unlocks
 * are left alone (they are how the recipe book works).
 *
 * <p>The vanilla <em>tabs</em> in the advancement screen cannot be removed by a plugin; they are removed in
 * spigot.yml. {@link #writeSnippet()} writes the exact lines to paste there.
 */
public final class VanillaAdvancements implements Listener {

    private final KMCCore plugin;

    public VanillaAdvancements(KMCCore plugin) { this.plugin = plugin; }

    @EventHandler(priority = EventPriority.LOWEST, ignoreCancelled = true)
    public void onGrant(PlayerAdvancementCriterionGrantEvent e) {
        if (!plugin.getConfig().getBoolean("achievements.block-vanilla-advancements", true)) return;
        var key = e.getAdvancement().getKey();
        if (!"minecraft".equals(key.getNamespace())) return;
        if (key.getKey().startsWith("recipes/")) return;
        e.setCancelled(true);
    }

    /** Writes {@code plugins/KMCCore/vanilla-advancements.yml}: the block for spigot.yml that hides the vanilla tabs. */
    public void writeSnippet() {
        try {
            List<String> keys = new ArrayList<>();
            for (Iterator<Advancement> it = Bukkit.advancementIterator(); it.hasNext(); ) {
                var k = it.next().getKey();
                if ("minecraft".equals(k.getNamespace()) && !k.getKey().startsWith("recipes/")) keys.add(k.toString());
            }
            if (keys.isEmpty()) return;
            java.util.Collections.sort(keys);
            StringBuilder sb = new StringBuilder();
            sb.append("# Paste this under \"advancements:\" in spigot.yml (replace \"disabled:\"), then restart the server.\n");
            sb.append("# It removes the vanilla advancement tabs, so only the KMC tabs are left. Generated by KMCCore.\n");
            sb.append("advancements:\n  disable-saving: false\n  disabled:\n");
            for (String k : keys) sb.append("  - ").append(k).append('\n');
            Files.writeString(new File(plugin.getDataFolder(), "vanilla-advancements.yml").toPath(), sb.toString());
        } catch (IOException | RuntimeException e) {
            plugin.getLogger().fine("Could not write vanilla-advancements.yml: " + e.getMessage());
        }
    }
}
